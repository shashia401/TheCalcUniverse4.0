const JOINT: Record<number, number[]> = Object.fromEntries(
  Object.entries(JOINT_ROWS).map(([age, s]) => [age, s.split(' ').map(Number)]),
);

export const JOINT_OWNER_MAX_AGE = 105;

/** Table III divisor; ages below 72 use the age-72 value (never needed after the start age), 120+ -> 2.0. */
export function uniformFactor(age: number): number {
  return UNIFORM[Math.min(Math.max(Math.trunc(age), 72), 120)];
}

/** True when the spouse is more than 10 years younger (the Table II condition) and inside the table's range. */
export function jointTableApplies(ownerAge: number, spouseAge: number): boolean {
  return Number.isFinite(spouseAge) && ownerAge - spouseAge > 10 && spouseAge >= JOINT_SPOUSE_MIN_AGE;
}

/** Table II divisor for the owner/spouse ages (owner clamped to 72-105; spouse clamped into the row). */
export function jointFactor(ownerAge: number, spouseAge: number): number {
  const o = Math.min(Math.max(Math.trunc(ownerAge), 72), JOINT_OWNER_MAX_AGE);
  const row = JOINT[o];
  const s = Math.min(Math.max(Math.trunc(spouseAge), JOINT_SPOUSE_MIN_AGE), JOINT_SPOUSE_MIN_AGE + row.length - 1);
  return row[s - JOINT_SPOUSE_MIN_AGE];
}

/** Distribution period for the year: Table II when a >10-year-younger sole-beneficiary spouse is given, else Table III. */
export function distributionPeriod(ownerAge: number, spouseAge: number | null): number {
  return spouseAge !== null && jointTableApplies(ownerAge, spouseAge)
    ? jointFactor(ownerAge, spouseAge)
    : uniformFactor(ownerAge);
}

/**
 * RMD start age by birth year (SECURE 2.0 sec. 107): 1951-1959 -> 73, 1960 or later -> 75. The statute is
 * ambiguous for 1959; the IRS's 2024 proposed regulations apply 73. Born 1950 or earlier: 72 (earlier cohorts
 * started at 70.5, but every such owner is past 72 now, so the same Uniform table applies).
 */
export function rmdStartAge(birthYear: number): number {
  if (birthYear <= 1950) return 72;
  if (birthYear <= 1959) return 73;
  return 75;
}

export interface ProjectionRow {
  year: number;
  age: number;
  balance: number;
  rmd: number;
  factor: number;
}

/**
 * Ten-year projection for an owner already at or past the RMD start age. `balance` is the prior-Dec-31 balance the year's RMD is computed from. Assumes the RMD is
 * withdrawn at the start of the year and the remainder grows at `rate` over the year.
 */
export function projectRmds(
  balance: number,
  currentAge: number,
  spouseAge: number | null,
  startYear: number,
  rate: number,
): ProjectionRow[] {
  const rows: ProjectionRow[] = [];
  let bal = balance;
  for (let i = 0; i < 10; i++) {
    const age = currentAge + i;
    const factor = distributionPeriod(age, spouseAge === null ? null : spouseAge + i);
    const rmd = bal / factor;
    rows.push({ year: startYear + i, age, balance: bal, rmd, factor });
    bal = (bal - rmd) * (1 + rate);
  }
  return rows;
}
